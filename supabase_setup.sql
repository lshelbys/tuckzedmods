-- 7. Atomic download counter
CREATE OR REPLACE FUNCTION public.increment_mod_downloads(p_id TEXT)
RETURNS INTEGER
LANGUAGE plpgsql
AS $$
DECLARE
  next_count INTEGER;
BEGIN
  UPDATE public.mods
  SET downloads = COALESCE(downloads, 0) + 1,
      updated_at = NOW()
  WHERE id = p_id
  RETURNING downloads INTO next_count;
  RETURN COALESCE(next_count, 0);
END;
$$;

-- 8. Keep mods.likes in sync with mod_likes rows
CREATE OR REPLACE FUNCTION public.sync_mod_likes_count()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
  target_mod TEXT;
  next_count INTEGER;
BEGIN
  target_mod := COALESCE(NEW.mod_id, OLD.mod_id);
  SELECT COUNT(*)::INTEGER INTO next_count FROM public.mod_likes WHERE mod_id = target_mod;
  UPDATE public.mods SET likes = next_count, updated_at = NOW() WHERE id = target_mod;
  RETURN NULL;
END;
$$;

DROP TRIGGER IF EXISTS trg_sync_mod_likes_count ON public.mod_likes;
CREATE TRIGGER trg_sync_mod_likes_count
AFTER INSERT OR DELETE ON public.mod_likes
FOR EACH ROW EXECUTE PROCEDURE public.sync_mod_likes_count();

-- 9. Touch mods.updated_at on row updates
CREATE OR REPLACE FUNCTION public.touch_mods_updated_at()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
  NEW.updated_at = NOW();
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_touch_mods_updated_at ON public.mods;
CREATE TRIGGER trg_touch_mods_updated_at
BEFORE UPDATE ON public.mods
FOR EACH ROW EXECUTE PROCEDURE public.touch_mods_updated_at();
